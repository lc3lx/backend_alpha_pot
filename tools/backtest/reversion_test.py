#!/usr/bin/env python3
"""
The decisive comparison: does the short-horizon mean reversion that is real on interbank
EUR/USD also exist in the prices Quotex quotes?

Independent vendor data (Twelve Data, 5000 bars of genuine 1-minute EUR/USD) showed one
rule — fade the last bar, hold five minutes — winning 57.4%, holding at 58.0% on sealed
data it was never selected on. That is not folklore; short-horizon reversion is a
documented feature of FX microstructure.

Whether it can be TRADED here is a different question with three parts, and this script
answers the first two:

  1. Do Quotex's REAL (non-OTC) pairs show it? They are supposed to track the interbank
     market, so the vendor result predicts they should.
  2. Do Quotex's OTC pairs show it? Those prices are generated by the broker rather than
     observed, so there is no reason they must.

The third part cannot be settled by any backtest: the broker chooses the strike. On the
vendor data this edge died at one to two pips of adverse pricing, so even where the
pattern exists, whether it survives contact with the counterparty's quoting is decided
live, in small size, not here.

Every rule below is scored on train and sealed halves separately. Nothing is selected on
the sealed half.
"""
from __future__ import annotations

import argparse
import sys

from backtest import ASSUMED_PAYOUT, CANDLE_DIR, Ctx, load_series, wilson
from sweep import score, split_series

BREAKEVEN = 1.0 / (1.0 + ASSUMED_PAYOUT)


def fade_last_bar(ctx):
    """The rule that survived on real EUR/USD. No filters: filters cost sample size."""
    return "put" if ctx.close() > ctx.open() else "call"


def fade_two_bars(ctx):
    """Fade only after two bars the same way — a slightly stronger stretch."""
    up1 = ctx.close() > ctx.open()
    up2 = ctx.close(1) > ctx.open(1)
    if up1 and up2:
        return "put"
    if not up1 and not up2:
        return "call"
    return None


def fade_body(ctx):
    """Fade a decisive bar only: body at least 60% of its range."""
    if ctx.body_fraction() < 0.6:
        return None
    return "put" if ctx.close() > ctx.open() else "call"


def fade_z(ctx):
    """Fade a bar that is large relative to the symbol's own recent volatility."""
    z = ctx.z_move(20)
    if z >= 1.0:
        return "put"
    if z <= -1.0:
        return "call"
    return None


def momentum_z(ctx):
    """The mirror, which won on real 60s data. Included so both signs are on one page."""
    z = ctx.z_move(20)
    if z >= 1.5:
        return "call"
    if z <= -1.5:
        return "put"
    return None


RULES = [
    ("fade last bar", fade_last_bar),
    ("fade 2 same-way bars", fade_two_bars),
    ("fade decisive bar (body>=60%)", fade_body),
    ("fade z>=1.0", fade_z),
    ("momentum z>=1.5", momentum_z),
]


def line(tag, w, l, t):
    n = w + l
    if n < 30:
        return f"    {tag:<22} n={n:<5} too few to judge"
    lo, hi = wilson(w, n)
    edge = (w * ASSUMED_PAYOUT - l) / (n + t)
    mark = "PROFITABLE" if lo > BREAKEVEN else ("thin" if w / n > BREAKEVEN else "loses")
    return (f"    {tag:<22} n={n:<5} win={w/n*100:5.1f}%  "
            f"CI=[{lo*100:4.1f},{hi*100:4.1f}]  edge={edge*100:+6.1f}%  {mark}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", default=CANDLE_DIR)
    ap.add_argument("--period", type=int, default=60)
    args = ap.parse_args()

    everything = load_series(args.dir, period=args.period)
    groups = {
        "QUOTEX REAL PAIRS (should track interbank)":
            [s for s in everything if "_otc" not in s.symbol],
        "QUOTEX OTC PAIRS (broker-generated prices)":
            [s for s in everything if "_otc" in s.symbol],
    }

    print(f"Breakeven at {ASSUMED_PAYOUT*100:.0f}% payout: {BREAKEVEN*100:.1f}%")
    print("Reference, real interbank EUR/USD from Twelve Data: fade last bar / 300s")
    print("  won 57.4% overall and 58.0% on sealed data (n=1936).")

    for title, series_list in groups.items():
        if not series_list:
            print(f"\n{title}\n  no data")
            continue
        train, test = split_series(series_list)
        print("\n" + "=" * 100)
        print(f"{title}")
        print(f"symbols={len({s.symbol for s in series_list})}  "
              f"bars={sum(len(s) for s in series_list)}")
        print("=" * 100)
        for hold in (1, 5):
            print(f"\n  hold {hold} bar(s) = {hold*args.period}s option")
            for name, rule in RULES:
                print(f"  {name}")
                print(line("train", *score(train, rule, hold)))
                print(line("SEALED", *score(test, rule, hold)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
