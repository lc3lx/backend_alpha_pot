#!/usr/bin/env python3
"""
Does the series contain ANY exploitable structure? Asked directly, not through indicators.

The grid search tested 1,800 combinations of z-scores, RSI, wicks and trend filters and
found nothing that survived a holdout. That is strong evidence about THAT family of rules
and weak evidence about the series, because a different family might see what moving
averages cannot. So instead of proposing more indicators, this measures the properties any
profitable rule would have to feed on. If they are absent, no indicator can manufacture
them, and the search can stop being repeated.

Six tests, each answering a question an indicator cannot:

  1. Autocorrelation across 60 lags. A tradeable series has non-zero correlation
     somewhere. Checked at every lag with a 95% band, plus how many lags breach it
     against how many should by chance — 3 of 60 is noise, 30 is structure.

  2. Variance ratio. Under a random walk, variance grows linearly with horizon, so
     VR(k) = 1. Below 1 means mean reversion, above means trending. This detects drift
     an indicator rule would only stumble on.

  3. Runs test. Are up/down streaks the length a coin flip produces? A generator with
     memory gives too few long runs or too many.

  4. Conditional probabilities over ALL patterns of the last k bars, k = 1..4. Thirty
     patterns, exhaustive, no indicator involved: if no sequence of four up/down bars
     shifts the next bar's odds, nothing built on bar direction can work. This is the
     test the grid search could not perform.

  5. Periodicity by minute and hour. A synthetic feed is generated by code, and code can
     have cycles. Real markets have session effects.

  6. Cross-symbol divergence. The one strategy family never tested: when two normally
     correlated symbols separate, does the gap close? Needs no predictability in either
     symbol alone, so the earlier null result does not rule it out.

Each test reports what chance alone would produce, because on 78,000 bars something always
looks remarkable until it is compared against that.
"""
from __future__ import annotations

import argparse
import math
import sys
from collections import defaultdict

from backtest import ASSUMED_PAYOUT, CANDLE_DIR, load_series, wilson

BREAKEVEN = 1.0 / (1.0 + ASSUMED_PAYOUT)


def returns(closes):
    return [(closes[i] - closes[i - 1]) / closes[i - 1]
            for i in range(1, len(closes)) if closes[i - 1]]


def autocorrelation(series_list, max_lag=60):
    """Pooled across symbols, so each lag gets every symbol's worth of evidence."""
    print("\n" + "=" * 100)
    print("1. AUTOCORRELATION OF RETURNS")
    print("   A series nobody can predict has none at any lag.")
    print("=" * 100)

    all_rets = []
    for s in series_list:
        all_rets.append(returns(s.c))
    total = sum(len(r) for r in all_rets)
    if total < 500:
        print("  too little data")
        return

    # Pooled estimate: sum covariances across symbols rather than averaging per-symbol
    # coefficients, which would weight a 200-bar symbol like a 600-bar one.
    breaches = []
    for lag in range(1, max_lag + 1):
        num = den = 0.0
        n_used = 0
        for rets in all_rets:
            if len(rets) <= lag + 10:
                continue
            m = sum(rets) / len(rets)
            num += sum((rets[i] - m) * (rets[i - lag] - m) for i in range(lag, len(rets)))
            den += sum((r - m) ** 2 for r in rets)
            n_used += len(rets) - lag
        if den <= 0 or n_used < 100:
            continue
        ac = num / den
        band = 1.96 / math.sqrt(n_used)
        if abs(ac) > band:
            breaches.append((lag, ac, band))

    expected = max_lag * 0.05
    print(f"  lags tested:            {max_lag}")
    print(f"  lags breaching 95% band: {len(breaches)}")
    print(f"  expected by chance:      {expected:.1f}")
    if breaches:
        print("  breaching lags (largest first):")
        for lag, ac, band in sorted(breaches, key=lambda x: -abs(x[1]))[:8]:
            # A coefficient this small cannot pay an 85% payout however real it is.
            print(f"    lag {lag:>3}: {ac:+.4f}  (band ±{band:.4f})")
    if len(breaches) <= expected * 1.5:
        print("  -> consistent with no linear predictability at any lag.")
    else:
        print("  -> more structure than chance; magnitudes above decide if it is tradeable.")


def variance_ratio(series_list, horizons=(2, 4, 8, 16, 32)):
    print("\n" + "=" * 100)
    print("2. VARIANCE RATIO  (=1 random walk, <1 mean reverting, >1 trending)")
    print("=" * 100)
    for k in horizons:
        ratios = []
        weights = []
        for s in series_list:
            r = returns(s.c)
            if len(r) < k * 20:
                continue
            var1 = sum(x * x for x in r) / len(r)
            agg = [sum(r[i:i + k]) for i in range(0, len(r) - k + 1)]
            if not agg or var1 <= 0:
                continue
            vark = sum(x * x for x in agg) / len(agg)
            ratios.append((vark / k) / var1)
            weights.append(len(r))
        if not ratios:
            continue
        vr = sum(v * w for v, w in zip(ratios, weights)) / sum(weights)
        # Under the null, VR(k) is asymptotically normal with this standard error.
        n = sum(weights) / len(weights)
        se = math.sqrt(2 * (2 * k - 1) * (k - 1) / (3 * k * n))
        z = (vr - 1) / se if se else 0.0
        verdict = "random walk" if abs(z) < 1.96 else (
            "MEAN REVERTING" if vr < 1 else "TRENDING")
        print(f"  horizon {k:>3} bars: VR={vr:.4f}  z={z:+6.2f}  {verdict}")


def runs_test(series_list):
    print("\n" + "=" * 100)
    print("3. RUNS TEST  (are up/down streaks the length a coin flip gives?)")
    print("=" * 100)
    observed = defaultdict(int)
    ups = downs = 0
    for s in series_list:
        dirs = [1 if s.c[i] > s.c[i - 1] else (0 if s.c[i] < s.c[i - 1] else None)
                for i in range(1, len(s.c))]
        dirs = [d for d in dirs if d is not None]
        ups += sum(dirs)
        downs += len(dirs) - sum(dirs)
        if not dirs:
            continue
        run = 1
        for i in range(1, len(dirs)):
            if dirs[i] == dirs[i - 1]:
                run += 1
            else:
                observed[min(run, 6)] += 1
                run = 1
        observed[min(run, 6)] += 1
    total_runs = sum(observed.values())
    total_moves = ups + downs
    if not total_runs or not total_moves:
        print("  no data")
        return
    p_up = ups / total_moves
    print(f"  moves: {total_moves}  up={p_up*100:.1f}%  runs={total_runs}")
    print(f"  {'length':<8}{'observed':>10}{'expected':>10}{'ratio':>8}")
    for length in range(1, 7):
        # P(run of exactly L) for a fair-ish coin, both directions.
        if length < 6:
            p = (p_up ** length) * (1 - p_up) + ((1 - p_up) ** length) * p_up
        else:
            p = (p_up ** 6) + ((1 - p_up) ** 6)
        exp = p * total_runs
        obs = observed[length]
        ratio = obs / exp if exp else 0.0
        tag = "" if 0.9 < ratio < 1.1 else "  <-- departs"
        label = f"{length}" if length < 6 else "6+"
        print(f"  {label:<8}{obs:>10}{exp:>10.0f}{ratio:>8.2f}{tag}")


def conditional_patterns(series_list, hold=1, max_k=4, min_count=200):
    """
    P(next bar up | the last k bars' up/down pattern), for every pattern.

    Exhaustive over bar-direction patterns rather than over indicators, so it answers the
    question the grid search structurally could not: is there ANY sequence of recent bars
    that tilts the next one?
    """
    print("\n" + "=" * 100)
    print(f"4. CONDITIONAL PROBABILITY BY PATTERN  (hold {hold} bar(s))")
    print(f"   Exhaustive over up/down patterns. Breakeven {BREAKEVEN*100:.1f}%.")
    print("=" * 100)
    for k in range(1, max_k + 1):
        table = defaultdict(lambda: [0, 0])
        for s in series_list:
            c = s.c
            for i in range(k, len(c) - hold):
                pattern = tuple(1 if c[i - j] > c[i - j - 1] else 0 for j in range(k))
                nxt = c[i + hold]
                if nxt == c[i]:
                    continue
                table[pattern][0 if nxt > c[i] else 1] += 1
        rows = []
        for pattern, (up, down) in table.items():
            n = up + down
            if n < min_count:
                continue
            rate = up / n
            lo, hi = wilson(up, n)
            # Tradeable only if the WHOLE interval clears breakeven, in either direction.
            edge = (lo > BREAKEVEN) or (hi < 1 - BREAKEVEN)
            rows.append((abs(rate - 0.5), pattern, rate, n, lo, hi, edge))
        if not rows:
            continue
        rows.sort(reverse=True)
        tradeable = sum(1 for r in rows if r[6])
        print(f"\n  k={k}: {len(rows)} patterns with >={min_count} samples, "
              f"{tradeable} tradeable")
        for _, pattern, rate, n, lo, hi, edge in rows[:4]:
            bits = "".join("U" if b else "D" for b in pattern)
            mark = "  <-- TRADEABLE" if edge else ""
            print(f"    {bits:<6} n={n:<7} P(up)={rate*100:5.1f}%  "
                  f"CI=[{lo*100:4.1f},{hi*100:4.1f}]{mark}")


def periodicity(series_list, hold=1):
    print("\n" + "=" * 100)
    print("5. PERIODICITY  (a generated feed can have cycles; sessions have effects)")
    print("=" * 100)
    for label, bucket in (("minute of hour", 60), ("hour of day", 24)):
        table = defaultdict(lambda: [0, 0])
        for s in series_list:
            for i in range(1, len(s.c) - hold):
                t = s.times[i]
                key = (t // 60) % 60 if bucket == 60 else (t // 3600) % 24
                nxt = s.c[i + hold]
                if nxt == s.c[i]:
                    continue
                table[key][0 if nxt > s.c[i] else 1] += 1
        rows = []
        for key, (up, down) in table.items():
            n = up + down
            if n < 150:
                continue
            lo, hi = wilson(up, n)
            rows.append((key, up / n, n, lo, hi))
        if not rows:
            continue
        extreme = sum(1 for _, _, _, lo, hi in rows if lo > BREAKEVEN or hi < 1 - BREAKEVEN)
        rows.sort(key=lambda r: -abs(r[1] - 0.5))
        print(f"\n  by {label}: {len(rows)} buckets, {extreme} with an interval clear of "
              f"breakeven")
        for key, rate, n, lo, hi in rows[:4]:
            print(f"    {key:>3}: n={n:<7} P(up)={rate*100:5.1f}%  "
                  f"CI=[{lo*100:4.1f},{hi*100:4.1f}]")


def divergence(series_list, hold=1, min_overlap=300, top=6):
    """
    The untested family: when two correlated symbols separate, does the gap close?

    Needs no predictability in either symbol on its own, so the earlier null results leave
    it open. Pairs are selected on the first 60% and the trade is scored on the last 40%,
    since picking the pair and scoring it on the same bars is the same selection trap the
    grid search fell into.
    """
    print("\n" + "=" * 100)
    print("6. CROSS-SYMBOL DIVERGENCE  (pairs trading, untested by the indicator sweep)")
    print("=" * 100)

    by_time = {}
    for s in series_list:
        by_time[s.symbol] = dict(zip(s.times, s.c))

    symbols = sorted(by_time)
    pairs = []
    for a_i in range(len(symbols)):
        for b_i in range(a_i + 1, len(symbols)):
            a, b = symbols[a_i], symbols[b_i]
            shared = sorted(set(by_time[a]) & set(by_time[b]))
            if len(shared) < min_overlap:
                continue
            cut = int(len(shared) * 0.6)
            tr = shared[:cut]
            ra = [by_time[a][t] for t in tr]
            rb = [by_time[b][t] for t in tr]
            da = returns(ra)
            db = returns(rb)
            n = min(len(da), len(db))
            if n < 100:
                continue
            ma, mb = sum(da[:n]) / n, sum(db[:n]) / n
            cov = sum((da[i] - ma) * (db[i] - mb) for i in range(n))
            va = math.sqrt(sum((x - ma) ** 2 for x in da[:n]))
            vb = math.sqrt(sum((x - mb) ** 2 for x in db[:n]))
            if va <= 0 or vb <= 0:
                continue
            corr = cov / (va * vb)
            pairs.append((abs(corr), corr, a, b, shared, cut))

    if not pairs:
        print("  no symbol pairs share enough timestamps")
        return
    pairs.sort(reverse=True)
    print(f"  pairs with >={min_overlap} shared bars: {len(pairs)}")
    print(f"  highest |correlation| on the training part: {pairs[0][0]:.3f} "
          f"({pairs[0][2]} vs {pairs[0][3]})")
    print("\n  Trading the top correlated pairs on SEALED bars: when the spread's z-score")
    print("  exceeds 1.5, bet the stretched leg reverts.")
    print(f"  {'pair':<28}{'corr':>7}{'n':>7}{'win':>8}{'CI':>16}")

    agg_w = agg_l = 0
    for _, corr, a, b, shared, cut in pairs[:top]:
        sealed = shared[cut:]
        if len(sealed) < hold + 40:
            continue
        ca = [by_time[a][t] for t in sealed]
        cb = [by_time[b][t] for t in sealed]
        # Spread of normalised logs, so the two price scales are comparable.
        spread = [math.log(x) - math.log(y) for x, y in zip(ca, cb) if x > 0 and y > 0]
        if len(spread) < hold + 40:
            continue
        w = l = 0
        for i in range(30, len(spread) - hold):
            window = spread[i - 30:i + 1]
            m = sum(window) / len(window)
            sd = math.sqrt(sum((x - m) ** 2 for x in window) / (len(window) - 1))
            if sd <= 0:
                continue
            z = (spread[i] - m) / sd
            if abs(z) < 1.5:
                continue
            # Spread high => leg A rich => expect A down.
            side = "put" if z > 0 else "call"
            entry, settle = ca[i], ca[i + hold]
            if settle == entry:
                continue
            if (settle > entry) == (side == "call"):
                w += 1
            else:
                l += 1
        if w + l < 30:
            continue
        agg_w += w
        agg_l += l
        lo, hi = wilson(w, w + l)
        print(f"  {a[:13]}/{b[:13]:<14}{corr:+7.2f}{w+l:>7}{w/(w+l)*100:>7.1f}%"
              f"   [{lo*100:4.1f},{hi*100:4.1f}]")

    if agg_w + agg_l:
        n = agg_w + agg_l
        lo, hi = wilson(agg_w, n)
        verdict = "TRADEABLE" if lo > BREAKEVEN else "not tradeable"
        print(f"\n  pooled across pairs: n={n}  win={agg_w/n*100:.1f}%  "
              f"CI=[{lo*100:.1f},{hi*100:.1f}]  {verdict}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", default=CANDLE_DIR)
    ap.add_argument("--period", type=int, default=60)
    ap.add_argument("--universe", choices=("otc", "real", "all"), default="otc")
    ap.add_argument("--hold", type=int, default=1)
    ap.add_argument("--skip-divergence", action="store_true")
    args = ap.parse_args()

    everything = load_series(args.dir, period=args.period, min_bars=150)
    if args.universe == "otc":
        series_list = [s for s in everything if "_otc" in s.symbol]
    elif args.universe == "real":
        series_list = [s for s in everything if "_otc" not in s.symbol]
    else:
        series_list = everything
    if not series_list:
        print("no data", file=sys.stderr)
        return 1

    print("=" * 100)
    print(f"STRUCTURE ANALYSIS  universe={args.universe}  period={args.period}s")
    print(f"symbols={len({s.symbol for s in series_list})}  "
          f"bars={sum(len(s) for s in series_list)}")
    print(f"breakeven at {ASSUMED_PAYOUT*100:.0f}% payout = {BREAKEVEN*100:.1f}%")
    print("=" * 100)

    autocorrelation(series_list)
    variance_ratio(series_list)
    runs_test(series_list)
    conditional_patterns(series_list, hold=args.hold)
    periodicity(series_list, hold=args.hold)
    if not args.skip_divergence:
        divergence(series_list, hold=args.hold)
    return 0


if __name__ == "__main__":
    sys.exit(main())
